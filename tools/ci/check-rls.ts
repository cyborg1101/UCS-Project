/**
 * check:rls (K05-T08 / K-15)
 *
 * Every table in a module schema must have BOTH `ENABLE` and `FORCE` row level
 * security plus at least one policy. A table with RLS off, or enabled but not
 * forced, silently lets the owner read across tenants - which is exactly the
 * class of bug this gate exists to stop.
 *
 * Exemptions are explicit and documented; anything not listed must comply.
 */
import { Client } from 'pg';
import { resolve } from 'node:path';

export interface RlsFinding {
  schema: string;
  table: string;
  problem: string;
}

/** Schemas owned by a business module - generated by the module generator. */
export const MODULE_SCHEMAS = ['sample'];

/**
 * Tables that are deliberately not tenant-scoped:
 *  - platform.tenant : the tenant registry itself (root of isolation)
 *  - audit.audit_entry : protected by append-only triggers instead of RLS
 */
export const EXEMPT_TABLES: Array<{ schema: string; table: string; reason: string }> = [
  { schema: 'platform', table: 'tenant', reason: 'tenant registry is the root of isolation' },
  { schema: 'audit', table: 'audit_entry', reason: 'append-only triggers protect it' },
  { schema: 'kernel', table: 'job_schedule', reason: 'kernel-global timer queue' },
  { schema: 'messaging', table: 'event_log', reason: 'global ordered log, relay-owned' },
  { schema: 'messaging', table: 'log_counter', reason: 'single global counter row' },
  { schema: 'messaging', table: 'writer_lease', reason: 'cluster-wide lease row' },
  { schema: 'messaging', table: 'event_dedup', reason: 'global dedup by event_id' },
  { schema: 'public', table: 'schema_migrations', reason: 'migration bookkeeping' },
];

function isExempt(schema: string, table: string): boolean {
  return EXEMPT_TABLES.some((e) => e.schema === schema && e.table === table);
}

export async function findRlsViolations(client: Client, schemas = MODULE_SCHEMAS): Promise<RlsFinding[]> {
  const { rows } = await client.query<{
    schema: string;
    table: string;
    relrowsecurity: boolean;
    relforcerowsecurity: boolean;
    policies: string;
  }>(
    `SELECT n.nspname AS schema,
            c.relname AS table,
            c.relrowsecurity,
            c.relforcerowsecurity,
            coalesce((SELECT count(*)::text FROM pg_policy p WHERE p.polrelid = c.oid), '0') AS policies
       FROM pg_class c
       JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE c.relkind = 'r'
        -- Partitions inherit RLS from their parent; the flag is not set on the
        -- child, so checking children would report false positives.
        AND NOT c.relispartition
        AND n.nspname = ANY($1::text[])
      ORDER BY n.nspname, c.relname`,
    [schemas],
  );

  const findings: RlsFinding[] = [];
  for (const r of rows) {
    if (isExempt(r.schema, r.table)) continue;
    if (!r.relrowsecurity) {
      findings.push({ schema: r.schema, table: r.table, problem: 'ROW LEVEL SECURITY is not enabled' });
      continue;
    }
    if (!r.relforcerowsecurity) {
      findings.push({
        schema: r.schema,
        table: r.table,
        problem: 'ROW LEVEL SECURITY is not FORCED (owner can read across tenants)',
      });
    }
    if (Number(r.policies) === 0) {
      findings.push({ schema: r.schema, table: r.table, problem: 'no RLS policy defined' });
    }
  }
  return findings;
}

async function main(): Promise<void> {
  const url =
    process.env.DATABASE_URL ??
    `postgres://migrator@${process.env.PGHOST ?? '127.0.0.1'}:${process.env.PGPORT ?? '5432'}/${process.env.PGDATABASE ?? 'ucs'}`;
  const client = new Client({ connectionString: url });
  await client.connect();
  try {
    const moduleSchemas = (process.env.MODULE_SCHEMAS ?? MODULE_SCHEMAS.join(',')).split(',');
    const findings = await findRlsViolations(client, ['sample', 'audit', ...moduleSchemas]);
    if (findings.length > 0) {
      console.error('check:rls FAILED');
      for (const f of findings) console.error(`  ${f.schema}.${f.table}: ${f.problem}`);
      process.exitCode = 1;
      return;
    }
    console.log(`check:rls OK (${moduleSchemas.join(', ')})`);
  } finally {
    await client.end();
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error('check:rls error:', err instanceof Error ? err.message : err);
    process.exit(1);
  });
}

export const _paths = { cwd: resolve() };
